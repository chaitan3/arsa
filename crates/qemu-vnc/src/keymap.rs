/// VNC clients send X11 keysyms; QEMU's console speaks qnums.
pub fn keysym_to_qnum(keysym: u32) -> Option<u32> {
    KEYMAP_X112QNUM
        .binary_search_by_key(&(keysym as u32), |&(k, _)| k)
        .ok()
        .map(|i| KEYMAP_X112QNUM[i].1 as u32)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn common_keys() {
        // XK_a = 0x61 -> KEY_A(30) -> qnum 0x1e
        assert_eq!(keysym_to_qnum(0x61), Some(0x1e));
        assert_eq!(keysym_to_qnum(0x20), Some(0x39)); // space
        assert_eq!(keysym_to_qnum(0xffbe), Some(0x3b)); // XK_F1 -> 0x3b
        assert_eq!(keysym_to_qnum(0x9999), None);
    }
}
